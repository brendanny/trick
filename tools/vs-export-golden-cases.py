#!/usr/bin/env python3
"""Export the conformance cases to C++ for the core library's golden replay test.

The golden replay test (trick_source/trick_utils/var_server/test/
GoldenReplay_test.cpp) runs each case of test/SIM_vs_conformance/
conformance/cases.py through the new parser and encoders and compares the
bytes with goldens/<name>.bin. It reads the cases from golden_cases.inc,
which this script writes. Run it after changing cases.py:

    tools/vs-export-golden-cases.py          # write the file
    tools/vs-export-golden-cases.py --check  # exit 1 if it is not current
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CASES_DIR = ROOT / "test" / "SIM_vs_conformance" / "conformance"
OUTPUT = (
    ROOT / "trick_source" / "trick_utils" / "var_server" / "test" / "golden_cases.inc"
)


def c_string(text: str) -> str:
    out = ['"']
    for ch in text.encode("utf-8"):
        c = chr(ch)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif 0x20 <= ch < 0x7F:
            out.append(c)
        else:
            out.append(f"\\{ch:03o}")
    out.append('"')
    return "".join(out)


def render() -> str:
    sys.path.insert(0, str(CASES_DIR))
    import cases

    lines = [
        "// Generated by tools/vs-export-golden-cases.py from",
        "// test/SIM_vs_conformance/conformance/cases.py. Do not edit.",
        "// VS_GOLDEN_CASE(name, script, expected_to_change)",
    ]
    for case in cases.CASES:
        changes = "true" if case.name in cases.EXPECTED_TO_CHANGE else "false"
        lines.append(f"VS_GOLDEN_CASE({c_string(case.name)},")
        lines.append(f"               {c_string(case.script())},")
        lines.append(f"               {changes})")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the file is not current"
    )
    args = parser.parse_args()

    text = render()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(ROOT)} is not current; run tools/vs-export-golden-cases.py"
            )
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
